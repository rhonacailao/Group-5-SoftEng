-- This is user management and permissions, intended for testing. This belongs to a later assigned task :)

BEGIN;
SET LOCAL search_path TO public;

CREATE TABLE public."role" (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(30) NOT NULL UNIQUE,
    description TEXT,
    status VARCHAR(8) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Inactive')),
    stamp TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);

CREATE TABLE public.app_user (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    username VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL,
    password_hash TEXT NOT NULL,
    role_id BIGINT NOT NULL REFERENCES public."role"(role_id) ON DELETE RESTRICT,
    status VARCHAR(10) NOT NULL DEFAULT 'Pending'
        CHECK (status IN ('Pending', 'Active', 'Inactive', 'Rejected')),
    is_blocked BOOLEAN NOT NULL DEFAULT FALSE,
    stamp TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CONSTRAINT app_user_username_nonempty CHECK (length(btrim(username)) > 0),
    CONSTRAINT app_user_email_nonempty CHECK (length(btrim(email)) > 0)
);

CREATE UNIQUE INDEX app_user_username_ci_uq ON public.app_user (lower(username));
CREATE UNIQUE INDEX app_user_email_ci_uq ON public.app_user (lower(email));

CREATE TABLE public.module (
    module_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_code VARCHAR(50) NOT NULL UNIQUE,
    module_name VARCHAR(100) NOT NULL,
    description TEXT,
    status VARCHAR(8) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Inactive')),
    stamp TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);

CREATE TABLE public.rights (
    right_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    right_code VARCHAR(80) NOT NULL UNIQUE,
    module_id BIGINT NOT NULL REFERENCES public.module(module_id) ON DELETE RESTRICT,
    description TEXT NOT NULL,
    status VARCHAR(8) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Inactive')),
    stamp TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);

CREATE TABLE public.user_permission (
    user_id BIGINT NOT NULL REFERENCES public.app_user(user_id) ON DELETE RESTRICT,
    right_id BIGINT NOT NULL REFERENCES public.rights(right_id) ON DELETE RESTRICT,
    status VARCHAR(8) NOT NULL DEFAULT 'Active'
        CHECK (status IN ('Active', 'Inactive')),
    stamp TEXT,
    granted_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    PRIMARY KEY (user_id, right_id)
);
CREATE INDEX user_permission_right_id_idx ON public.user_permission(right_id);
CREATE INDEX rights_module_id_idx ON public.rights(module_id);
CREATE INDEX app_user_role_id_idx ON public.app_user(role_id);

ALTER TABLE public."role" ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_user ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.module ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.rights ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.user_permission ENABLE ROW LEVEL SECURITY;

REVOKE ALL ON TABLE public."role" FROM anon, authenticated;
REVOKE ALL ON TABLE public.app_user FROM anon, authenticated;
REVOKE ALL ON TABLE public.module FROM anon, authenticated;
REVOKE ALL ON TABLE public.rights FROM anon, authenticated;
REVOKE ALL ON TABLE public.user_permission FROM anon, authenticated;

REVOKE ALL ON SEQUENCE public.role_role_id_seq FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.app_user_user_id_seq FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.module_module_id_seq FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.rights_right_id_seq FROM anon, authenticated;

COMMIT;
