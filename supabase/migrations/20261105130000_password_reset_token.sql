-- password-reset token (for review); and it requires app_user(user_id) to exist first
-- run only in Supabase testing

BEGIN;

CREATE TABLE public.password_reset_token (
    token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES public.app_user(user_id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    is_used BOOLEAN NOT NULL DEFAULT FALSE,
    used_at TIMESTAMPTZ,

    CONSTRAINT password_reset_token_hash_nonempty
        CHECK (length(btrim(token_hash)) > 0),
    CONSTRAINT password_reset_token_expiry_valid
        CHECK (expires_at > created_at),
    CONSTRAINT password_reset_token_used_consistent
        CHECK (is_used = (used_at IS NOT NULL))
);

CREATE INDEX password_reset_token_unused_user_idx
    ON public.password_reset_token (user_id, expires_at)
    WHERE is_used = FALSE;

ALTER TABLE public.password_reset_token ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON TABLE public.password_reset_token FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.password_reset_token_token_id_seq FROM anon, authenticated;

COMMIT;
